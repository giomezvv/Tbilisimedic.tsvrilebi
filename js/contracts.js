function cDateDotRaw(x) {
    if (!x) return '____';
    const d = new Date(x);
    return `${String(d.getDate()).padStart(2,'0')}.${String(d.getMonth()+1).padStart(2,'0')}.${d.getFullYear()}`;
}

function getContractTpl() {
    return CONTRACT_TEMPLATES.find(t => t.id === contractState.tplId) || CONTRACT_TEMPLATES[0];
}

