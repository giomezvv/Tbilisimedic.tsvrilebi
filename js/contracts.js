/* ==========================================
   გენერატორის გახსნა
   ========================================== */
function openContractModal(tplId) {
    closeContractPicker();
    contractState = { tplId: tplId || 'general', values: {}, schedule: [], products: [] };
    const tpl = getContractTpl();
    contractState.values.date = localISODate();
    if (tpl.productCols) contractState.products = [{}];

    document.getElementById('contractModalTitle').innerText = '📝 ' + tpl.title;
    buildContractForm();
    document.getElementById('contractModal').style.display = 'flex';
    generateContractPreview();
}

function closeContractModal() {
    document.getElementById('contractModal').style.display = 'none';
}

function backToContractPicker() {
    closeContractModal();
    openContractPicker();
}

/* ---------- ფორმის აწყობა ---------- */
function buildContractForm() {
    const tpl = getContractTpl();
    let html = '<div class="c-form-grid">';
    tpl.fields.forEach(f => {
        if (f.type === 'divider') {
            html += `<h4 class="c-form-divider">${f.label}</h4>`;
            return;
        }
        if (f.type === 'schedule') {
            html += `<div class="c-field c-full">
                        <label>${f.label}</label>
                        <div id="scheduleRowsContainer"></div>
                        <button class="btn-schedule" onclick="addScheduleRow()" style="margin-top:5px; width:100%;">➕ გრაფიკის დამატება</button>
                     </div>`;
            return;
        }
        if (f.type === 'products') {
            html += `<div class="c-field c-full">
                        <label>${f.label}</label>
                        <div id="productRowsContainer"></div>
                        <button class="btn-schedule" onclick="addProductRow()" style="margin-top:5px; width:100%;">➕ პროდუქციის დამატება</button>
                     </div>`;
            return;
        }
        const val = contractState.values[f.id] !== undefined ? contractState.values[f.id] : '';
        const cls = 'c-field' + (f.half ? ' c-half' : ' c-full');
        if (f.type === 'textarea') {
            html += `<div class="${cls}"><label>${f.label}</label>
                     <textarea id="cf_${f.id}" rows="4" placeholder="${f.ph||''}" oninput="onContractInput('${f.id}', this.value)">${escapeHtml(val)}</textarea></div>`;
        } else {
            html += `<div class="${cls}"><label>${f.label}</label>
                     <input type="${f.type}" id="cf_${f.id}" value="${escapeHtml(val)}" placeholder="${f.ph||''}" oninput="onContractInput('${f.id}', this.value)"></div>`;
        }
    });
    html += '</div>';
    document.getElementById('contractFormArea').innerHTML = html;
    renderScheduleRows();
    renderProductRows();
}

function onContractInput(id, val) {
    contractState.values[id] = val;
    generateContractPreview();
}

/* ---------- გადახდის გრაფიკი ---------- */
function addScheduleRow() {
    contractState.schedule.push({ date: '', amount: '' });
    renderScheduleRows();
    generateContractPreview();
}
function removeScheduleRow(i) {
    contractState.schedule.splice(i, 1);
    renderScheduleRows();
    generateContractPreview();
}
function onScheduleInput(i, key, val) {
    contractState.schedule[i][key] = val;
    generateContractPreview();
}
function renderScheduleRows() {
    const c = document.getElementById('scheduleRowsContainer');
    if (!c) return;
    c.innerHTML = contractState.schedule.map((s, i) => `
        <div class="schedule-row">
            <input type="date" value="${escapeHtml(s.date)}" oninput="onScheduleInput(${i},'date',this.value)">
            <input type="number" value="${escapeHtml(s.amount)}" placeholder="თანხა (₾)" style="width:120px;" oninput="onScheduleInput(${i},'amount',this.value)">
            <button class="btn-schedule" style="color:red;" onclick="removeScheduleRow(${i})">✕</button>
        </div>
    `).join('');
}

/* ---------- პროდუქციის სტრიქონები ---------- */
function addProductRow() {
    contractState.products.push({});
    renderProductRows();
    generateContractPreview();
}
function removeProductRow(i) {
    contractState.products.splice(i, 1);
    renderProductRows();
    generateContractPreview();
}
function onProductInput(i, key, val) {
    contractState.products[i][key] = val;
    generateContractPreview();
}
function renderProductRows() {
    const c = document.getElementById('productRowsContainer');
    if (!c) return;
    const cols = getContractTpl().productCols;
    if (!cols) { c.innerHTML = ''; return; }
    const editable = cols.filter(x => x.key !== 'total');
    c.innerHTML = contractState.products.map((p, i) => `
        <div class="c-prod-row">
            <div class="c-prod-head">
                <span>#${i + 1}</span>
                <button class="btn-schedule" style="color:red; padding:2px 8px;" onclick="removeProductRow(${i})">✕</button>
            </div>
            ${editable.map(col => `
                <input type="${(col.key==='price'||col.key==='qty')?'number':'text'}"
                       value="${escapeHtml(p[col.key])}"
                       placeholder="${col.label}"
                       oninput="onProductInput(${i},'${col.key}',this.value)">
            `).join('')}
        </div>
    `).join('');
}

/* ---------- პრევიუ ---------- */
function generateContractPreview() {
    const tpl = getContractTpl();
    document.getElementById('contractPrintArea').innerHTML = tpl.body();
}

