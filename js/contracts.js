/* ---------- პროდუქციის ცხრილი ---------- */
function productRowsHtml(cols, minRows) {
    const list = contractState.products;
    let rows = '';
    let n = 0;
    list.forEach((p) => {
        n++;
        let tds = `<td>${n}</td>`;
        cols.forEach(c => {
            let val = p[c.key] !== undefined && p[c.key] !== '' ? p[c.key] : '';
            if (c.key === 'total') {
                const t = (parseFloat(p.price)||0) * (parseFloat(p.qty)||0);
                val = t > 0 ? t.toLocaleString('ka-GE', {maximumFractionDigits:2}) : '';
            } else if (c.money && val !== '') {
                val = (parseFloat(val)||0).toLocaleString('ka-GE', {maximumFractionDigits:2});
            }
            tds += `<td>${escapeHtml(val)}</td>`;
        });
        rows += `<tr>${tds}</tr>`;
    });
    for (let i = list.length; i < (minRows || 0); i++) {
        rows += `<tr><td>&nbsp;</td>${cols.map(()=>'<td></td>').join('')}</tr>`;
    }
    return rows;
}
function productTableHtml(cols, widths, minRows) {
    return `<table class="c-table c-nobreak" data-cols="${widths}">
                <thead>
                    <tr><th>#</th>${cols.map(c=>`<th>${c.label}</th>`).join('')}</tr>
                </thead>
                <tbody>${productRowsHtml(cols, minRows)}</tbody>
            </table>`;
}

