function cV(id) { return escapeHtml((contractState.values[id] || '').toString().trim()); }
function cF(id, fb) { const x = cV(id); return x ? x : fb; }
function cN(id) { return parseFloat(contractState.values[id]) || 0; }

function cDateSlash(id, fb) {
    const x = cV(id);
    if (!x) return fb || '__ / __ / 202_ წ.';
    const d = new Date(x);
    return `${String(d.getDate()).padStart(2,'0')} / ${String(d.getMonth()+1).padStart(2,'0')} / ${d.getFullYear()} წ.`;
}
function cDateDot(id, fb) {
    const x = cV(id);
    if (!x) return fb || '__.__.____';
    const d = new Date(x);
    return `${String(d.getDate()).padStart(2,'0')}.${String(d.getMonth()+1).padStart(2,'0')}.${d.getFullYear()}`;
}
function cDateGeoUntil(id, fb) {
    const x = cV(id);
    if (!x) return fb || '____________';
    const d = new Date(x);
    const m = ["იანვრამდე","თებერვლამდე","მარტამდე","აპრილამდე","მაისამდე","ივნისამდე","ივლისამდე","აგვისტომდე","სექტემბრამდე","ოქტომბრამდე","ნოემბრამდე","დეკემბრამდე"];
    return `${d.getFullYear()} წლის ${d.getDate()} ${m[d.getMonth()]}`;
}
function cMoney(val, fb) {
    const n = parseFloat(val) || 0;
    if (n <= 0) return fb || '____ (____)';
    return `${n.toLocaleString('ka-GE', {maximumFractionDigits: 2})} (${numToWordsGE(Math.floor(n))})`;
}
function cMoneyId(id, fb) { return cMoney(contractState.values[id], fb); }

